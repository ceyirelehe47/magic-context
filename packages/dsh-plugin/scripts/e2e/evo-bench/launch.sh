# Round 37 phase 2 — evo bench: how the agent's DSH process is launched (sourced by
# run.sh and probe.sh so the access probe exercises EXACTLY the launch the bench uses).
#
#   evo_isolation_setup              (once per run, after WS / SCR / DSH_HOME exist)
#   evo_dsh_turn <log> <timeout-s> <dsh args...>     (cwd = $WS)
#   evo_patch <file>                 (path of a --patch file as the launched DSH sees it)
#
# Needs: WS (agent workspace), SCR (controller scratch of this run), DSH_BIN, DSH_HOME,
# E2E_ROOT, XDG_*. EVO_ISOLATE=1 (default) runs the agent behind real access boundaries:
#
#   1. the WHOLE DSH process runs in a bwrap mount namespace that contains only the
#      system dirs (read-only), the DSH runtime (read-only), DSH's own storage
#      (DSH_HOME, XDG dirs: sessions, Magic Context DB — read-write, the host needs
#      them), the workspace (read-write), the test wrapper and the isolation files.
#      NOT mounted at all: the controller's task dir (every later item), the bench
#      output dir (proxy request log / bodies / responses / turn logs / meta), the
#      controller scratch (snapshots), the repo checkout (scripts, workflows, docs,
#      git history) and the rest of the runner home. Patch files are copied in.
#   2. every bash command the agent runs goes through DSH's own confined executor
#      (DSH_PERMISSION_MODE=workspace-write, approval policy never = no escalation)
#      whose runner (dsh-sandbox-local `runnerCommand`) is evo-runner: DSH's bwrap
#      profile plus a tmpfs over E2E_ROOT — the DSH runtime, the session store and
#      the Magic DB are not visible to the agent's commands;
#   3. ripgrep (the grep / glob tools spawn it unconfined) is replaced inside the
#      namespace by a wrapper that runs the real binary under the same tmpfs;
#   4. the in-process file tools (read / write / edit / read_image) resolve every
#      model path through ctx.fs.resolve, fenced by the bench-only evo-fs-fence
#      plugin (hiddenRoots = E2E_ROOT).
#   The API key never enters the namespace: DSH gets a dummy key, the recording
#   proxy (outside) sets the real Authorization header (BENCH_UPSTREAM_KEY).
# EVO_ISOLATE=0 is the pre-round-37 plain launch (whole runner filesystem visible).
EVO_BWRAP="${EVO_BWRAP:-bwrap}"

evo_isolated() { [[ "${EVO_ISOLATE:-1}" == 1 ]]; }

# Copy a patch file where the namespace can read it (the checkout is not mounted).
evo_patch() {
  if ! evo_isolated; then echo "$1"; return; fi
  mkdir -p "$SCR/iso/patches"
  local dst="$SCR/iso/patches/$(basename "$1")"
  cp "$1" "$dst"; echo "$dst"
}

evo_isolation_setup() {
  evo_isolated || return 0
  local here; here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
  local iso="$SCR/iso"; mkdir -p "$iso/patches" "$SCR/home"
  command -v "$EVO_BWRAP" >/dev/null || { echo "::error::evo isolation: bwrap not found"; return 1; }
  EVO_HIDE="$(cd "$E2E_ROOT" && pwd)"
  # the patch files the HOST loads at boot (model routes, plugin-group patch, this isolation
  # layout) are controller config: hidden from the agent's tools like E2E_ROOT (run 42365663370:
  # the agent cat'ed them looking for requirement hints). evo-runner / rg-fence stay visible.
  EVO_HIDE_PATCHES="$iso/patches"
  # 2. bash runner: DSH's bwrap profile args, then the hide mounts, then the command
  cat > "$iso/evo-runner" <<RUN
#!/usr/bin/env bash
# evo bench bash runner (dsh-sandbox-local runnerCommand). Generated by launch.sh.
pre=(); while [[ \$# -gt 0 && "\$1" != "--" ]]; do pre+=("\$1"); shift; done
[[ "\$1" == "--" ]] || { echo "evo-runner: no command separator" >&2; exit 125; }
exec "$EVO_BWRAP" "\${pre[@]}" --tmpfs "$EVO_HIDE" --tmpfs "$EVO_HIDE_PATCHES" "\$@"
RUN
  # 3. ripgrep wrapper over every packaged rg binary
  local rg
  RG_BINS=()
  while IFS= read -r rg; do RG_BINS+=("$(readlink -f "$rg")"); done < <(find -L "$E2E_ROOT/dsh/node_modules" -maxdepth 4 -path '*@vscode/ripgrep-*/bin/rg' -type f 2>/dev/null)
  if [[ ${#RG_BINS[@]} -gt 0 ]]; then
    cp "${RG_BINS[0]}" "$iso/rg.real"
    cat > "$iso/rg-fence" <<RG
#!/bin/sh
# evo bench ripgrep wrapper (grep / glob tools). Generated by launch.sh.
exec "$EVO_BWRAP" --ro-bind / / --dev /dev --proc /proc --unshare-pid --die-with-parent --tmpfs "$EVO_HIDE" --tmpfs "$EVO_HIDE_PATCHES" -- "$iso/rg.real" "\$@"
RG
  fi
  chmod +x "$iso/evo-runner" "$iso/rg-fence" 2>/dev/null
  # 4. in-process fs fence plugin, in every bench profile
  local p
  for p in "$DSH_HOME"/profiles/*/; do
    mkdir -p "$p/node_modules"; rm -rf "$p/node_modules/evo-fs-fence"
    cp -r "$here/isolation/evo-fs-fence" "$p/node_modules/evo-fs-fence"
  done
  cat > "$iso/patches/evo-isolation.yml" <<YML
# evo bench isolation (generated by launch.sh; bench only)
- id: sandbox
  config:
    runnerCommand: ["$iso/evo-runner"]
    runnerFailureSignatures: ["evo-runner:", "bwrap:"]
- id: approval
  config:
    policy: never
# workspace-write + never is not one of the shipped presets: name it, or the permission
# presets entry refuses to activate ("match no preset; configure defaultPreset")
- id: permission
  config:
    presets:
      read-only: { sandbox: read-only, approval: ask }
      workspace-write: { sandbox: workspace-write, approval: ask }
      danger-full-access: { sandbox: danger-full-access, approval: never }
      evo-isolated: { sandbox: workspace-write, approval: never }
    defaultPreset: evo-isolated
- insert:
    - id: evo-fs-fence
      name: evo-fs-fence
      config:
        hiddenRoots: ["$EVO_HIDE", "$EVO_HIDE_PATCHES"]
YML
  EVO_ISO_PATCH="$iso/patches/evo-isolation.yml"
  export DSH_PERMISSION_MODE=workspace-write
}

evo_isolation_args() {
  local a=(--die-with-parent --unshare-pid --unshare-ipc --unshare-uts --dev /dev --proc /proc --tmpfs /tmp --dir /var)
  local d
  for d in /usr /etc /opt /snap; do [[ -d "$d" ]] && a+=(--ro-bind "$d" "$d"); done
  for d in /bin /sbin /lib /lib32 /lib64 /libx32; do
    if [[ -L "$d" ]]; then a+=(--symlink "$(readlink "$d")" "$d"); elif [[ -d "$d" ]]; then a+=(--ro-bind "$d" "$d"); fi
  done
  [[ -d /run/systemd/resolve ]] && a+=(--ro-bind /run/systemd/resolve /run/systemd/resolve)
  [[ -S /run/docker.sock ]] && a+=(--bind /run/docker.sock /run/docker.sock --symlink ../run /var/run)
  # toolchains outside /usr and /opt (node / bwrap of a local install)
  local bin
  for bin in node "$EVO_BWRAP" zstd; do
    bin="$(command -v "$bin" 2>/dev/null)" || continue; bin="$(dirname "$(readlink -f "$bin")")"
    case "$bin" in /usr/*|/opt/*|/snap/*|/bin|/sbin) ;; *) a+=(--ro-bind "$bin" "$bin") ;; esac
  done
  # host: DSH runtime (ro) + its own storage (rw)
  a+=(--ro-bind "$E2E_ROOT/dsh" "$E2E_ROOT/dsh" --bind "$DSH_HOME" "$DSH_HOME")
  for d in "$XDG_CONFIG_HOME" "$XDG_DATA_HOME" "$XDG_STATE_HOME" "$XDG_CACHE_HOME"; do a+=(--bind "$d" "$d"); done
  # agent: workspace (rw), test wrapper + isolation files (ro), a private HOME
  a+=(--bind "$WS" "$WS" --ro-bind "$SCR/iso" "$SCR/iso" --bind "$SCR/home" "$SCR/home")
  [[ -d "$SCR/bin" ]] && a+=(--ro-bind "$SCR/bin" "$SCR/bin")
  local rg
  for rg in "${RG_BINS[@]}"; do a+=(--ro-bind "$SCR/iso/rg-fence" "$rg"); done
  # environment: an ALLOWLIST, not a blocklist (round 37). The DSH process starts from an
  # empty environment (--clearenv) and gets back only what the host needs; the controller's
  # variables (BENCH_OUT, BENCH_*, EVO_*, GITHUB_* / RUNNER_* / ACTIONS_* run metadata, the
  # upstream key, anything exported later) never reach DSH or any tool the agent runs
  # (smoke 42362017411: the agent's `env` showed BENCH_OUT and the run metadata).
  # Residual boundary (accepted 2026-11-07 18:30 CST): DSH_* / XDG_* VALUES name host paths
  # (DSH_HOME, XDG_DATA_HOME...); the directories themselves stay hidden from the agent.
  a+=(--clearenv)
  local v
  while IFS= read -r v; do
    [[ "$v" =~ ^(PATH|LANG|LANGUAGE|LC_[A-Z]+|TERM|USER|LOGNAME|SHELL|TZ|NO_COLOR|DSH_[A-Z0-9_]+|XDG_[A-Z_]+|OPENCODE_SESSION|OPENCODE_DB|MAGIC_CONTEXT_[A-Z0-9_]+|MC_[A-Z0-9_]+|MOCK_LLM_PORT|MOCK_LLM_KEY|DOCKER_HOST|NODE_OPTIONS|HTTPS?_PROXY|NO_PROXY|https?_proxy|no_proxy)$ ]] || continue
    a+=(--setenv "$v" "${!v}")
  done < <(compgen -e)
  a+=(--setenv HOME "$SCR/home" --setenv OPENCODE_API_KEY "proxy-injects-the-key" --chdir "$WS")
  printf '%s\0' "${a[@]}"
}

# Probe storage (round 37 phase 2): the access probe must not share DSH_HOME (session
# store, storages) or the Magic Context data dir with the paid run of the same job.
# Fresh dirs under E2E_ROOT (hidden from the agent like the paid store); profiles and
# the plugin config are copied, sessions / storages / DB are not.
evo_probe_storage() {
  local nonce="$1" root
  [[ -n "$nonce" ]] || { echo "evo_probe_storage: nonce required" >&2; return 1; }
  root="$E2E_ROOT/probe-store/$nonce"
  rm -rf "$root"; mkdir -p "$root/home" "$root/xdg/config" "$root/xdg/data" "$root/xdg/state" "$root/xdg/cache"
  [[ -d "$DSH_HOME/profiles" ]] && cp -a "$DSH_HOME/profiles" "$root/home/profiles" || return 1
  [[ -d "$XDG_CONFIG_HOME" ]] && cp -a "$XDG_CONFIG_HOME/." "$root/xdg/config/"
  EVO_PROBE_STORE="$root"
  export DSH_HOME="$root/home" XDG_CONFIG_HOME="$root/xdg/config" XDG_DATA_HOME="$root/xdg/data" XDG_STATE_HOME="$root/xdg/state" XDG_CACHE_HOME="$root/xdg/cache"
}
evo_probe_storage_cleanup() {
  [[ -n "${EVO_PROBE_STORE:-}" && "$EVO_PROBE_STORE" == "$E2E_ROOT"/probe-store/* ]] || return 0
  rm -rf "$EVO_PROBE_STORE"
  rmdir "$E2E_ROOT/probe-store" 2>/dev/null
  return 0
}

evo_dsh_turn() {
  local log="$1" t="$2"; shift 2
  if evo_isolated; then
    local a=()
    while IFS= read -r -d '' x; do a+=("$x"); done < <(evo_isolation_args)
    # the isolation patch goes right after --profile <p> (DSH takes options before the task)
    local head=()
    [[ "${1:-}" == --profile ]] && { head=("$1" "$2"); shift 2; }
    (cd "$WS" && timeout -k 30 "$t" "$EVO_BWRAP" "${a[@]}" -- node "$DSH_BIN" "${head[@]}" --patch "$EVO_ISO_PATCH" "$@" > "$log" 2>&1)
  else
    (cd "$WS" && timeout -k 30 "$t" node "$DSH_BIN" "$@" > "$log" 2>&1)
  fi
}
