#!/usr/bin/env bash
# Round 36 cache bench driver: ONE run of one group.
#
#   cache-bench/bench.sh <plugin|baseline> <run-label> <out-dir>
#
# Preconditions (dsh-cache-bench.yml): env.sh environment, DSH bootstrapped;
# plugin group: profile "test" with the plugin installed + `setup`; baseline
# group: profile "base" = the shipped headless template, no plugin.
# OPENCODE_API_KEY in the environment (never printed; the proxy never logs
# headers).
#
# Task (identical in both groups): turn 1 "ready", then up to MAX_TURNS-1
# turns of eight ~7.6 KB generated fixtures (the scenario P corpus,
# byte-identical generator), one read call per step. Every turn is a fresh
# `dsh` process on the same session (as in ci-e2e.sh). The driver stops after
# the turn in which the FIRST compaction started: plugin = first historian
# request (bench-hist route), baseline = first compaction-basic summarizer
# request / session `compaction/start`. Each run gets a fresh random
# BENCH_NONCE (prepended to the system prompt by the proxy) and a fresh
# OPENCODE_SESSION, by the same rule in both groups.
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
source "$HERE/../env.sh"
MODE="$1"; LABEL="$2"; OUT="$3"
MAX_TURNS="${MAX_TURNS:-9}"
RUN_TIMEOUT="${RUN_TIMEOUT:-400}"
mkdir -p "$OUT"
case "$MODE" in
  plugin) PROFILE=test; PATCHES=(--patch "$HERE/bench-model.yml" --patch "$HERE/bench-plugin.yml") ;;
  baseline) PROFILE=base; PATCHES=(--patch "$HERE/bench-model.yml") ;;
  *) echo "mode must be plugin|baseline" >&2; exit 2 ;;
esac

FIX="bench-fixtures"
python3 - "$FIX" <<'PY'
import hashlib, os, sys
d = sys.argv[1]
os.makedirs(d, exist_ok=True)
words = ("harbor lantern meadow granite orchard copper thistle saffron glacier willow "
         "ember quartz falcon juniper marble cobalt tundra velvet cedar prism").split()
for k in range(1, 65):
    lines = [f"# round 19 pressure fixture {k}/{40 if k <= 40 else 64} (generated by ci-e2e.sh)"]
    i = 0
    while sum(len(l) + 1 for l in lines) < 7500:
        seed = hashlib.sha256(f"p{k}:{i}".encode()).digest()
        lines.append(f"{i:03d} " + " ".join(words[b % len(words)] for b in seed[:10]) + ".")
        i += 1
    lines.append(f"CHECKSUM: P19-{k}-{hashlib.sha256(f'p19-{k}'.encode()).hexdigest()[:6].upper()}")
    open(os.path.join(d, f"p{k:02d}.txt"), "w").write("\n".join(lines) + "\n")
PY

export BENCH_NONCE="${BENCH_NONCE-$(python3 -c 'import secrets; print(secrets.token_hex(8))')}"
export OPENCODE_SESSION="mc-bench-$MODE-$LABEL-$(python3 -c 'import secrets; print(secrets.token_hex(4))')"
export MAGIC_CONTEXT_DEBUG_HISTORIAN=1
export MAGIC_CONTEXT_DSH_HISTORIAN_AWAIT_TURN_END_MS=60000
export BENCH_ABLATE="${BENCH_ABLATE-}"
printf '{"mode":"%s","label":"%s","nonce":"%s","session_header":"%s","profile":"%s","max_turns":%s,"ablate":"%s","native_roles":"%s","start":%s}\n' \
  "$MODE" "$LABEL" "$BENCH_NONCE" "$OPENCODE_SESSION" "$PROFILE" "$MAX_TURNS" "$BENCH_ABLATE" "${MAGIC_CONTEXT_DSH_NATIVE_ROLES-}" "$(date +%s%3N)" > "$OUT/meta.json"

node "$HERE/proxy.mjs" 18731 "$OUT" > "$OUT/proxy.out" 2>&1 &
PROXY=$!
for _ in $(seq 1 50); do (echo > /dev/tcp/127.0.0.1/18731) 2>/dev/null && break; sleep 0.1; done

turn() { # turn <n> <task> [sid]
  local name; name="turn-$(printf %02d "$1")"
  local args=(--profile "$PROFILE" "${PATCHES[@]}" "$2" --json)
  [[ -n "${3:-}" ]] && args+=(--session-id "$3")
  local s; s=$(date +%s.%N)
  timeout "$RUN_TIMEOUT" node "$DSH_BIN" "${args[@]}" > "$OUT/$name.log" 2>&1
  local rc=$?
  echo "rc=$rc elapsed=$(python3 -c "print(round($(date +%s.%N)-$s,1))")s" >> "$OUT/$name.log"
  echo "[bench $MODE $LABEL] $name rc=$rc"
}
sid_of() { python3 - "$1" <<'PY'
import json, sys
for line in open(sys.argv[1], errors="replace"):
    try: o = json.loads(line)
    except Exception: continue
    if o.get("type") == "session": print(o.get("sessionId", "")); break
PY
}
decode() { local f; f="$(ls "$DSH_HOME"/sessions/*/"$1"/session.v4.jsonl.zstd 2>/dev/null | head -n 1)"; [[ -n "$f" ]] && zstd -qdc "$f" > "$OUT/session.jsonl" 2>/dev/null; }
compacted() { # first compaction started? (proxy: historian/other request; session: compaction/start)
  grep -qE '"kind":"(historian|other)"' "$OUT/requests.jsonl" 2>/dev/null && return 0
  decode "$SID"; grep -q '"type":"compaction/start"' "$OUT/session.jsonl" 2>/dev/null
}

turn 1 "Reply with the single word: ready."
SID="$(sid_of "$OUT/turn-01.log")"
echo "$SID" > "$OUT/sid"
STOP="max-turns"
if [[ -n "$SID" ]]; then
  for t in $(seq 2 "$MAX_TURNS"); do
    b=$((t - 2))
    files="$(for j in 1 2 3 4 5 6 7 8; do printf '%s/p%02d.txt, ' "$FIX" $((b * 8 + j)); done | sed 's/, $//')"
    turn "$t" "Read each of these eight files with the read tool, ONE read call per step (wait for each result before the next call), in this order: $files. Do not call any tool other than read. Then reply with one line per file: <path>: <its CHECKSUM code>." "$SID"
    if compacted; then STOP="compaction-turn-$t"; break; fi
  done
else
  STOP="no-session"
fi
sleep 2; kill "$PROXY" 2>/dev/null; wait "$PROXY" 2>/dev/null
[[ -n "$SID" ]] && decode "$SID"
python3 - "$OUT/meta.json" "$STOP" <<'PY'
import json, sys, time
m = json.load(open(sys.argv[1])); m["stop"] = sys.argv[2]; m["end"] = int(time.time() * 1000)
json.dump(m, open(sys.argv[1], "w"))
PY
echo "[bench $MODE $LABEL] stop=$STOP requests=$(wc -l < "$OUT/requests.jsonl" 2>/dev/null || echo 0)"
