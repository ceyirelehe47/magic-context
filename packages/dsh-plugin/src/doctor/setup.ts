/**
 * doctor/setup — `dsh-magic-context setup` (DSH 0.2 layout).
 *
 * The DSH adapter's own setup tool (a package bin, NOT a dsh CLI command):
 *   1. locate the DSH install the `dsh` launcher runs from;
 *   2. pick the profile (`--profile`, or the only profile under $DSH_HOME);
 *   3. contract-scan the stock layout for that profile's flavour
 *      (flat: `@deepseek-ai/dsh-base` root `compaction-basic`; preset/web:
 *      `@deepseek-ai/dsh-web-app` `preset-standard`) — a mismatch FAILS
 *      CLOSED and nothing is written;
 *   4. make sure `dsh-magic-context` is in the profile's
 *      `dsh.profile.bundles` (only when the package is resolvable there);
 *   5. write the Magic rows as a managed block in the profile's own
 *      `cordis.patch.yml` (flat: disable compaction-basic + insert
 *      magic-compaction / magic-agent; web: a `magic-standard` agent preset);
 *   6. bootstrap/validate `~/.config/cortexkit/magic-context.jsonc` — never
 *      overwrites an existing file, only hints about missing keys.
 */
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { resolveCortexKitUserConfigPath } from "@magic-context/core/config/migrate-config-location";
import {
  parseJsonc,
  readJsoncFile,
} from "@magic-context/core/shared/jsonc-parser";
import {
  finishManagedLayer,
  hasItemAfterManagedBlock,
  mergeManagedBlock,
  readManagedBlock,
  removeManagedBlock,
  MAGIC_PRESET_ID,
} from "../compat/dsh-0.1/profile-patch";
import {
  DSH_COMPAT_EXPECTED_VERSION,
  MAGIC_CONTEXT_PACKAGE,
  errorMessage,
  listFlag,
  locateDshInstall,
  parseFlags,
  resolveDshHome,
  stringFlag,
  writeFileAtomic,
} from "./env";
import { listProfiles } from "./doctor";
import {
  compareManagedBlock,
  dumpEntryListYaml,
  parseEntryListYaml,
  planProfileWiring,
  type PresetSelectionChange,
} from "./profile-wiring";

export { dumpEntryListYaml, parseEntryListYaml };

/** Thin preset identity (dsh-reference §A.6 custom preset metadata). */
export const MAGIC_STANDARD_PRESET = {
  id: "magic-standard",
  name: "Magic Context standard",
  description:
    "Stock `standard` preset with the Magic Context compaction engine enabled " +
    "(compaction-basic disabled) and the Magic agent rows mounted.",
  order: 10,
} as const;

/** Recommended top-level keys checked when a user config already exists. */
export const RECOMMENDED_CONFIG_KEYS = [
  "enabled",
  "transform_mode",
  "sqlite",
  "embedding",
  "compaction",
] as const;

export type SetupStepStatus = "ok" | "warn" | "fail";

export interface SetupStep {
  readonly status: SetupStepStatus;
  readonly title: string;
  readonly detail: string;
}

export interface SetupReport {
  readonly exitCode: number;
  readonly steps: readonly SetupStep[];
  /** Files actually written by this run (empty on dry-run / failure). */
  readonly generatedFiles: readonly string[];
  readonly nextSteps: readonly string[];
}

export interface DshSetupOptions {
  readonly env?: NodeJS.ProcessEnv;
  /** DSH home override (tests / `--dsh-home`). */
  readonly dshHome?: string;
  /** DSH install override (tests / `--dsh-install`). */
  readonly dshInstallDir?: string;
  /** Validate + report but write nothing. */
  readonly dryRun?: boolean;
  /** Profile to wire (`--profile`). */
  readonly profile?: string;
}

/** Selection flags of a setup run (`--preset`, `--all-presets`, `--disable-preset`). */
export function selectionChangeOf(argv: readonly string[]): PresetSelectionChange {
  const { flags } = parseFlags(argv);
  return {
    add: listFlag(argv, "preset"),
    remove: listFlag(argv, "disable-preset"),
    all: flags["all-presets"] === true,
  };
}

/** Minimal, schema-valid user config (JSONC with a comment header). */
export function defaultMagicConfigJsonc(): string {
  return [
    "// Magic Context — generated by `dsh-magic-context setup`.",
    "// Shared by every harness (OpenCode, Pi, DSH). On DSH the Settings page",
    "// (Magic Context section) can OVERRIDE a few fields per profile; an unset",
    "// DSH field inherits this file (DSH override > this jsonc > core default).",
    "// DSH never writes this file.",
    "// Full schema: packages/plugin/src/config/schema/magic-context.ts",
    "{",
    '  "enabled": true,',
    '  "transform_mode": "ts",',
    '  "sqlite": { "cache_size_mb": 64, "mmap_size_mb": 0 },',
    '  "embedding": { "provider": "local", "model": "Xenova/all-MiniLM-L6-v2" },',
    '  "compaction": { "enabled": true }',
    "}",
    "",
  ].join("\n");
}

/** Keys the user explicitly carries; only used for the "missing key" hint. */
function presentTopLevelKeys(configPath: string): Set<string> {
  const parsed = readJsoncFile<Record<string, unknown>>(configPath);
  if (parsed === null || typeof parsed !== "object") return new Set();
  return new Set(Object.keys(parsed));
}

export async function runDshSetup(
  argv: readonly string[],
  options: DshSetupOptions = {},
): Promise<SetupReport> {
  const { flags } = parseFlags(argv);
  const env = options.env ?? process.env;
  const dshHome = options.dshHome ?? stringFlag(flags, "dsh-home") ?? resolveDshHome(env);
  const dshInstallDir = options.dshInstallDir ?? stringFlag(flags, "dsh-install");
  const dryRun = options.dryRun ?? flags["dry-run"] === true;
  let profile = options.profile ?? stringFlag(flags, "profile");

  const steps: SetupStep[] = [];
  const generatedFiles: string[] = [];
  let failed = false;
  let layoutLabel: string | undefined;

  // 1. DSH home.
  steps.push({ status: "ok", title: "DSH home", detail: dshHome });

  // 2. DSH install (launcher anchor).
  const located = locateDshInstall({ dshHome, dshInstallDir, env });
  if (located.dshInstallDir === undefined) {
    steps.push({
      status: "fail",
      title: "DSH install",
      detail:
        `Could not locate the @deepseek-ai/dsh launcher package ` +
        `(${DSH_COMPAT_EXPECTED_VERSION} expected). Probed:\n` +
        located.tried.map((candidate) => `  - ${candidate}`).join("\n") +
        `\nFix: install DSH ${DSH_COMPAT_EXPECTED_VERSION}, put \`dsh\` on PATH, or pass --dsh-install <dir>.`,
    });
    failed = true;
  } else {
    const versionOk = located.version === DSH_COMPAT_EXPECTED_VERSION;
    steps.push({
      status: versionOk ? "ok" : "warn",
      title: "DSH install",
      detail:
        `${located.dshInstallDir} (${located.version ?? "unknown version"}, found via ${located.source})` +
        (versionOk ? "" : ` — the adapter pins ${DSH_COMPAT_EXPECTED_VERSION}; the contract scan below decides.`),
    });
  }

  // 3. Profile selection.
  if (!failed && profile === undefined) {
    const profiles = listProfiles(dshHome);
    if (profiles.length === 1) {
      profile = profiles[0];
    } else {
      steps.push({
        status: "fail",
        title: "Profile",
        detail:
          profiles.length === 0
            ? `no profiles under ${join(dshHome, "profiles")}; boot one first (e.g. \`dsh --profile headless --dump-config\`).`
            : `several profiles (${profiles.join(", ")}); pass --profile <name>.`,
      });
      failed = true;
    }
  }

  // 4. Contract scan + wiring plan (fail closed).
  let plan: ReturnType<typeof planProfileWiring> | undefined;
  if (!failed && located.dshInstallDir !== undefined && profile !== undefined) {
    plan = planProfileWiring({ dshHome, dshInstallDir: located.dshInstallDir, profile, change: selectionChangeOf(argv) });
    layoutLabel = plan.layout === "flat" ? "flat (headless/tui root tree)" : "preset (web agent presets)";
    if (plan.issue !== undefined || (plan.blockBody === undefined && plan.selection.length > 0)) {
      steps.push({
        status: "fail",
        title: "Stock layout contract scan",
        detail:
          `${plan.scannedFile ?? plan.profileDir}: ${plan.issue ?? "no wiring derived"}. ` +
          `Refusing to write the profile patch (fail closed). Fix: check that the DSH install matches ${DSH_COMPAT_EXPECTED_VERSION}.`,
      });
      failed = true;
    } else {
      steps.push({
        status: "ok",
        title: "Stock layout contract scan",
        detail: `profile ${profile}: layout ${layoutLabel}; ${plan.scannedFile} matches the expected rows.`,
      });
      const before = plan.currentSelection === undefined ? "(not wired)" : plan.currentSelection.join(", ") || "(none)";
      steps.push({
        status: "ok",
        title: "Preset selection",
        detail:
          `Magic enabled in: ${plan.selection.length === 0 ? "(none — Magic rows will be removed)" : plan.selection.join(", ")} ` +
          `(was: ${before}); available: ${plan.availablePresets.join(", ")}` +
          (plan.unsupportedPresets !== undefined
            ? `; unsupported: ${Object.entries(plan.unsupportedPresets).map(([id, why]) => `${id} (${why})`).join("; ")}`
            : ""),
      });
    }
  }

  // 5. Bundle membership (the rows reference dsh-magic-context/* specifiers,
  //    so the package must resolve from the profile before anything is written).
  if (!failed && plan !== undefined) {
    const resolvable = [
      join(plan.profileDir, "node_modules", MAGIC_CONTEXT_PACKAGE, "package.json"),
      join(dshHome, "profiles", "node_modules", MAGIC_CONTEXT_PACKAGE, "package.json"),
    ].some((file) => existsSync(file));
    if (plan.bundles.includes(MAGIC_CONTEXT_PACKAGE)) {
      steps.push({
        status: resolvable ? "ok" : "fail",
        title: "Profile bundle",
        detail: resolvable
          ? `${MAGIC_CONTEXT_PACKAGE} is in dsh.profile.bundles and resolvable.`
          : `${MAGIC_CONTEXT_PACKAGE} is in dsh.profile.bundles but NOT installed in the profile.`,
      });
      if (!resolvable) failed = true;
    } else if (!resolvable) {
      steps.push({
        status: "fail",
        title: "Profile bundle",
        detail:
          `${MAGIC_CONTEXT_PACKAGE} is not installed in profile ${plan.profile}. ` +
          `Fix: dsh plugin --profile ${plan.profile} add ${MAGIC_CONTEXT_PACKAGE}, then re-run setup.`,
      });
      failed = true;
    } else if (dryRun) {
      steps.push({ status: "ok", title: "Profile bundle (dry run)", detail: `would add ${MAGIC_CONTEXT_PACKAGE} to ${plan.packageJsonPath}.` });
    } else {
      try {
        const pkg = JSON.parse(readFileSync(plan.packageJsonPath, "utf8")) as {
          dsh?: { profile?: { bundles?: string[] } };
        };
        pkg.dsh ??= {};
        pkg.dsh.profile ??= {};
        pkg.dsh.profile.bundles = [...(pkg.dsh.profile.bundles ?? []), MAGIC_CONTEXT_PACKAGE];
        writeFileAtomic(plan.packageJsonPath, `${JSON.stringify(pkg, null, 2)}\n`, 0o644);
        generatedFiles.push(plan.packageJsonPath);
        steps.push({ status: "ok", title: "Profile bundle", detail: `added ${MAGIC_CONTEXT_PACKAGE} to ${plan.packageJsonPath}.` });
      } catch (error) {
        steps.push({ status: "fail", title: "Profile bundle", detail: errorMessage(error) });
        failed = true;
      }
    }
  }

  // 6a. Empty selection: Magic disabled in every preset → remove the block
  //     (stock compaction-basic + token-meter come back; host rows stay).
  if (!failed && plan !== undefined && plan.blockBody === undefined && plan.selection.length === 0) {
    try {
      const existing = existsSync(plan.patchPath) ? readFileSync(plan.patchPath, "utf8") : undefined;
      if (existing === undefined || readManagedBlock(existing) === undefined) {
        steps.push({ status: "ok", title: "Profile patch layer", detail: `${plan.patchPath}: no managed block; nothing to remove.` });
      } else {
        const stripped = removeManagedBlock(existing);
        parseEntryListYaml(stripped);
        if (dryRun) {
          steps.push({ status: "ok", title: "Profile patch layer (dry run)", detail: `would remove the managed block from ${plan.patchPath}.` });
        } else {
          writeFileAtomic(plan.patchPath, stripped, 0o644);
          generatedFiles.push(plan.patchPath);
          steps.push({
            status: "ok",
            title: "Profile patch layer",
            detail: `removed the managed block from ${plan.patchPath} (stock compaction + token-meter restored in every preset).`,
          });
        }
      }
    } catch (error) {
      steps.push({ status: "fail", title: "Profile patch layer", detail: `${plan.patchPath}: ${errorMessage(error)}` });
      failed = true;
    }
  }

  // 6. Profile patch layer (managed block).
  if (!failed && plan !== undefined && plan.blockBody !== undefined) {
    try {
      const existing = existsSync(plan.patchPath) ? readFileSync(plan.patchPath, "utf8") : undefined;
      const currentBlock = existing === undefined ? undefined : readManagedBlock(existing);
      const comparison = currentBlock === undefined ? undefined : compareManagedBlock(currentBlock, plan.blockBody);
      if (
        existing !== undefined &&
        comparison !== undefined &&
        comparison.upToDate &&
        comparison.foreign.length === 0 &&
        hasItemAfterManagedBlock(existing)
      ) {
        steps.push({ status: "ok", title: "Profile patch layer", detail: `${plan.patchPath} already up to date (unchanged).` });
      } else {
        // Rows DSH's settings writer appended INSIDE the block are moved out
        // (right after the end marker), never dropped; an edit anchor keeps
        // later settings edits outside the block.
        const foreign = comparison?.foreign ?? [];
        const merged = finishManagedLayer(
          mergeManagedBlock(existing, plan.blockBody),
          foreign.length > 0 ? dumpEntryListYaml(foreign) : undefined,
        );
        // Round-trip parse: never leave a profile layer the loader cannot read.
        parseEntryListYaml(merged);
        if (dryRun) {
          steps.push({ status: "ok", title: "Profile patch layer (dry run)", detail: `would write the managed block into ${plan.patchPath}:\n${plan.blockBody}` });
        } else {
          writeFileAtomic(plan.patchPath, merged, 0o644);
          generatedFiles.push(plan.patchPath);
          steps.push({
            status: "ok",
            title: "Profile patch layer",
            detail:
              `wrote the managed block into ${plan.patchPath} (` +
              (plan.layout === "flat"
                ? "compaction-basic + token-meter disabled; magic-compaction, magic-agent, magic-meter inserted"
                : `Magic enabled in agent preset(s) ${plan.selection.join(", ")}; token-meter → magic-meter`) +
              ").",
          });
        }
      }
    } catch (error) {
      steps.push({ status: "fail", title: "Profile patch layer", detail: `${plan.patchPath}: ${errorMessage(error)}` });
      failed = true;
    }
  }

  // 5. Bootstrap / validate the user config (never overwrite an existing file).
  const configPath = resolveCortexKitUserConfigPath();
  if (existsSync(configPath)) {
    let missing: string[] = [];
    try {
      parseJsonc(readFileSync(configPath, "utf8"));
      const present = presentTopLevelKeys(configPath);
      missing = RECOMMENDED_CONFIG_KEYS.filter((key) => !present.has(key));
    } catch (error) {
      steps.push({
        status: "warn",
        title: "Magic Context user config",
        detail: `${configPath} exists but is not valid JSONC (${errorMessage(error)}); leaving untouched.`,
      });
      missing = [];
    }
    if (missing.length === 0) {
      steps.push({
        status: "ok",
        title: "Magic Context user config",
        detail: `${configPath} exists and carries the recommended keys; not overwritten.`,
      });
    } else {
      steps.push({
        status: "warn",
        title: "Magic Context user config",
        detail:
          `${configPath} exists; not overwritten. Missing recommended keys: ` +
          `${missing.join(", ")} (defaults apply).`,
      });
    }
  } else {
    if (failed) {
      steps.push({
        status: "warn",
        title: "Magic Context user config",
        detail:
          `${configPath} does not exist; not created because earlier steps ` +
          `failed (fail closed — nothing partial is written).`,
      });
    } else if (dryRun) {
      steps.push({
        status: "ok",
        title: "Magic Context user config (dry run)",
        detail: `${configPath} would be created from defaults.`,
      });
    } else {
      try {
        writeFileAtomic(configPath, defaultMagicConfigJsonc());
        generatedFiles.push(configPath);
        steps.push({
          status: "ok",
          title: "Magic Context user config",
          detail: `created ${configPath} from defaults.`,
        });
      } catch (error) {
        steps.push({
          status: "fail",
          title: "Magic Context user config",
          detail: `could not create ${configPath}: ${errorMessage(error)}`,
        });
        failed = true;
      }
    }
  }

  // 7. Next steps.
  const nextSteps: string[] = [];
  if (failed) {
    nextSteps.push("Fix the failing steps above, then re-run `dsh-magic-context setup`.");
  } else if (plan !== undefined) {
    nextSteps.push(`Check the composed tree: dsh --profile ${plan.profile} --dump-config | grep magic-`);
    if (plan.layout === "preset" && plan.selection.includes(MAGIC_PRESET_ID)) {
      nextSteps.push(
        `Select the \`${MAGIC_PRESET_ID}\` agent preset for new sessions (Settings → Agent preset).`,
      );
    }
    if (plan.layout === "preset" && plan.selection.some((id) => id !== MAGIC_PRESET_ID)) {
      nextSteps.push("New sessions of the patched stock presets run Magic Context; existing sessions keep their composition until restarted.");
    }
    nextSteps.push(`Verify with: dsh-magic-context doctor --profile ${plan.profile}`);
  }

  return {
    exitCode: failed ? 1 : 0,
    steps,
    generatedFiles,
    nextSteps,
  };
}
